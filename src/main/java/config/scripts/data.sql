create table inscripcion
(
    id              number(6) generated by default as identity, -- Codigo de 6 digitos
    id_cliente      number(3)    not null,
    id_experiencia  number(3)    not null,
    precio_total    number(8, 2) check (precio_total >= 0),
    saldo_pendiente number(8, 2) check (saldo_pendiente >= 0),
    fecha           timestamp,
    primary key (id),
    foreign key (id_cliente) references cliente (id),
    foreign key (id_experiencia) references experiencia (id)
