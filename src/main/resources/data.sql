drop table ciudad cascade constraints;
drop table estadio cascade constraints;
drop table confederacion cascade constraints;
drop table seleccion cascade constraints;
drop table partido cascade constraints;
drop table guia cascade constraints;
drop table experiencia cascade constraints;
drop table servicio cascade constraints;
drop table experiencia_servicio cascade constraints;
drop table experiencia_guia_suplente cascade constraints;
drop table cliente cascade constraints;
drop table inscripcion cascade constraints;
drop table inscripcion_servicio cascade constraints;
drop table impuesto cascade constraints;
drop table servicio_impuesto cascade constraints;
drop table pago cascade constraints;

create table pais
(
    id     number(3) generated by default as identity,
    nombre varchar2(100),
    primary key (id)
);

create table ciudad
(
    id      number(3) generated by default as identity,
    nombre  varchar2(100),
    id_pais number(3),
    primary key (id),
    foreign key (id_pais) references pais (id)
);

create table estadio
(
    id        number(3) generated by default as identity,
    nombre    varchar2(100),
    capacidad number(6),
    id_ciudad number(3),
    primary key (id),
    foreign key (id_ciudad) references ciudad (id)
);

create table confederacion
(
    id     number(3) generated by default as identity,
    nombre varchar2(100),
    primary key (id)
);

create table seleccion
(
    id               number(3) generated by default as identity,
    nombre           varchar2(100),
    id_confederacion number(3),
    primary key (id),
    foreign key (id_confederacion) references confederacion (id)
);

create table partido
(
    id                     number(3) generated by default as identity,
    id_estadio             number(3),
    fecha                  timestamp,
    id_seleccion_local     number(3),
    id_seleccion_visitante number(3),
    goles_local            number(2) check (goles_local >= 0),
    goles_visitante        number(2) check (goles_visitante >= 0),
    primary key (id),
    foreign key (id_estadio) references estadio (id),
    foreign key (id_seleccion_local) references seleccion (id),
    foreign key (id_seleccion_visitante) references seleccion (id),
    check (id_seleccion_local != id_seleccion_visitante)
);

create table guia
(
    id               number(3) generated by default as identity,
    tipo_documento   char(2) check (tipo_documento in ('CC', 'TI', 'CE', 'PA')), -- CC TI CE PA
    numero_documento number(12)    not null,
    nombre           varchar2(100) not null,
    nivel            varchar2(100) check (nivel in ('BASICO', 'INTERMEDIO', 'EXPERTO')),
    primary key (id),
    unique (tipo_documento, numero_documento)
);

create table experiencia
(
    id                number(3) generated by default as identity,
    id_partido        number(3),
    id_guia_principal number(3),
    descripcion       varchar2(100),
    estado            varchar2(20) check (estado in ('DISPONIBLE', 'AGOTADA', 'CANCELADA')),
    precio_base       number(8, 2) check (precio_base >= 0),
    cupos_totales     number(6) check (cupos_totales > 0),
    cupos_disponibles number(6),
    primary key (id),
    foreign key (id_partido) references partido (id),
    foreign key (id_guia_principal) references guia (id)
);

create table servicio
(
    id          number(3) generated by default as identity,
    nombre      varchar2(100) not null,
    descripcion varchar2(100),
    costo       number(8, 2) check (costo >= 0),
    primary key (id)
);

create table experiencia_servicio
(
    id_experiencia number(3),
    id_servicio    number(3),
    primary key (id_experiencia, id_servicio),
    foreign key (id_servicio) references servicio (id),
    foreign key (id_experiencia) references experiencia (id)
);

create table experiencia_guia_suplente
(
    id_experiencia number(3),
    id_guia        number(3),
    primary key (id_experiencia, id_guia),
    foreign key (id_guia) references guia (id),
    foreign key (id_experiencia) references experiencia (id)
);

create table cliente
(
    id               number(3) generated by default as identity,
    tipo_documento   char(2) check (tipo_documento in ('CC', 'TI', 'CE', 'PA')),
    numero_documento number(12)    not null,
    nombre_completo  varchar2(100) not null,
    correo           varchar2(100),
    telefono         varchar2(20),
    primary key (id)
);

create table inscripcion
(
    id             number(3) generated by default as identity,
    id_cliente     number(3) not null,
    id_experiencia number(3) not null,
    fecha          timestamp,
    primary key (id),
    foreign key (id_cliente) references cliente (id),
    foreign key (id_experiencia) references experiencia (id)
);

create table inscripcion_servicio
(
    id_inscripcion number(3),
    id_servicio    number(3),
    cantidad       number(2) check (cantidad > 0),
    costo_unitario number(8, 2) check (costo_unitario >= 0),
    primary key (id_servicio, id_inscripcion),
    foreign key (id_servicio) references servicio (id),
    foreign key (id_inscripcion) references inscripcion (id)
);

create table impuesto
(
    id            number(3) generated by default as identity,
    tipo_impuesto varchar2(50) check (tipo_impuesto in ('IVA', 'TURISTICO', 'LOCAL', 'OTRO')),
    porcentaje    number(5, 2) check (porcentaje >= 0 and porcentaje <= 100), -- 22.5% ej
    primary key (id)
);

create table servicio_impuesto
(
    id_servicio number(3),
    id_impuesto number(3),
    primary key (id_servicio, id_impuesto),
    foreign key (id_impuesto) references impuesto (id),
    foreign key (id_servicio) references servicio (id)
);

create table pago
(
    id             number(3) generated by default as identity,
    id_inscripcion number(3) not null,
    metodo         varchar2(100) check (metodo in ('TARJETA CREDITO', 'TARJETA DEBITO', 'EFECTIVO',
                                                   'BILLETERA DIGITAL')), -- tarjeta credito, tarjeta debito, efectivo, billetera digital
    referencia     varchar2(100),
    valor_pagado   number(8, 2) check (valor_pagado >= 0),
    fecha          timestamp,
    primary key (id),
    foreign key (id_inscripcion) references inscripcion (id)
);

