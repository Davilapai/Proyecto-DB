-- Valida cupos e inicializa precio_total/saldo_pendiente con precio_base
create or replace trigger trg_act_cupos_disp
before insert on inscripcion
for each row
declare
    v_cupos       number;
    v_precio_base number(8, 2);
begin
    if inserting then
        select cupos_disponibles, precio_base
        into v_cupos, v_precio_base
        from experiencia
        where id = :new.id_experiencia;

        if v_cupos <= 0 then
            raise_application_error(-20001, 'error: no hay cupos disponibles para esta experiencia.');
        end if;

        update experiencia
        set cupos_disponibles = cupos_disponibles - 1
        where id = :new.id_experiencia;

        :new.precio_total    := v_precio_base;
        :new.saldo_pendiente := v_precio_base;
    end if;
end;
/

-- Descuenta el saldo pendiente al registrar un pago
create or replace trigger trg_saldo_pendiente
after insert on pago
for each row
declare
    v_saldo number(8, 2);
begin
    if inserting then
        select saldo_pendiente
        into v_saldo
        from inscripcion
        where id = :new.id_inscripcion;

        v_saldo := v_saldo - :new.valor_pagado;

        update inscripcion
        set saldo_pendiente = v_saldo
        where id = :new.id_inscripcion;
    end if;
end;
/

-- Recalcula precio_total y saldo_pendiente al agregar/modificar/eliminar servicios
create or replace trigger trg_calcular_precio_total
    after insert or update or delete on inscripcion_servicio
    for each row
declare
    v_porcentaje number(10, 2);
    v_delta      number(10, 2);
    v_id_ins     number;
    v_id_serv    number;
begin
    if deleting then
        v_id_ins  := :old.id_inscripcion;
        v_id_serv := :old.id_exp_servicio;
        v_delta   := -(:old.cantidad * :old.costo_unitario);
    else
        v_id_ins  := :new.id_inscripcion;
        v_id_serv := :new.id_exp_servicio;
        v_delta   := (:new.cantidad * :new.costo_unitario);
        if updating then
            v_delta := v_delta - (:old.cantidad * :old.costo_unitario);
        end if;
    end if;

    select nvl(sum(imp.porcentaje), 0)
    into v_porcentaje
    from experiencia_servicio es
        join servicio_impuesto si on si.id_servicio = es.id_servicio
        join impuesto imp         on imp.id = si.id_impuesto
    where es.id = v_id_serv;

    v_delta := v_delta * (1 + v_porcentaje / 100);

    update inscripcion
    set precio_total    = precio_total    + v_delta,
        saldo_pendiente = saldo_pendiente + v_delta
    where id = v_id_ins;
end;
/

-- Agrega al historial cuando se modifica un servicio de inscripcion (UPDATE)
create or replace trigger trg_historial_modificacion
    after update on inscripcion_servicio
    for each row
declare
    v_id_cliente number;
begin
    select i.id_cliente
    into v_id_cliente
    from inscripcion i
    where i.id = :new.id_inscripcion;

    insert into historial_cliente (id_cliente, id_inscripcion, descripcion)
    values (v_id_cliente,
            :new.id_inscripcion,
            'Modificacion en servicios de inscripcion #' || :new.id_inscripcion);
end;
/

-- Agrega al historial automaticamente al registrar una nueva inscripcion
create or replace trigger trg_historial_nueva_inscripcion
    after insert on inscripcion
    for each row
begin
    insert into historial_cliente (id_cliente, id_inscripcion, descripcion)
    values (:new.id_cliente,
            :new.id,
            'Nueva inscripcion registrada a experiencia #' || :new.id_experiencia);
end;
/


