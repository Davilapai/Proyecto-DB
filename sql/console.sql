-- 2 Clientes con mayor numero de inscripciones
select  c.id,
        c.nombre_completo   as Cliente,
        count(i.id)         as Total_Inscripciones

from cliente c
         join inscripcion i on i.id_cliente = c.id

group by c.id, c.nombre_completo
having count(i.id) = (
    select max(Total_Inscripciones)
    from (
             select count(*) as Total_Inscripciones
             from inscripcion
             group by id_cliente
         )
);

-- Asumimos que cada experiencia dura 4 horas
-- 3 Ingresos generados por cada guia en las experiencias
select g.id,
       g.nombre,
       SUM(
               CASE
                   WHEN g.nivel = 'BASICO' THEN 15
                   WHEN g.nivel = 'INTERMEDIO' THEN 30
                   WHEN g.nivel = 'EXPERTO' THEN 60
                   END
       ) * 4 AS Ingresos
from experiencia e
         join guia g on e.id_guia_principal = g.id
group by g.id, g.nombre;

-- 4 Calculo de impuestos asociados a las inscripciones
select to_char(i.id)                              as ID_Inscripcion,
       cl.nombre_completo                         as Cliente,
       s.nombre                                   as Servicio,
       to_char(ins.cantidad)                      as cantidad,
       to_char(ins.costo_unitario)                as costo_unitario,
       to_char(ins.cantidad * ins.costo_unitario) as Subtotal,
       imp.tipo_impuesto,
       to_char(imp.porcentaje)                    as porcentaje,

       to_char(
               round(
                       ins.cantidad * ins.costo_unitario
                           * imp.porcentaje / 100,
                       2
               )
       )                                          as Valor_Impuesto

from inscripcion i
         join cliente cl on cl.id = i.id_cliente
         join inscripcion_servicio ins on ins.id_inscripcion = i.id
         join servicio s on s.id = ins.id_exp_servicio
         join servicio_impuesto si on si.id_servicio = s.id
         join impuesto imp on imp.id = si.id_impuesto

union all

select 'Total' as ID_Inscripcion,
       '-'     as Cliente,
       '-'     as Servicio,
       '-'     as cantidad,
       '-'     as costo_unitario,
       to_char(
               sum(ins.cantidad * ins.costo_unitario)
       )       as Subtotal,
       '-'     as tipo_impuesto,
       '-'     as porcentaje,
       to_char(
               round(
                       sum(
                               ins.cantidad * ins.costo_unitario
                                   * imp.porcentaje / 100
                       ),
                       2
               )
       )       as Valor_Impuesto

from inscripcion i
         join cliente cl on cl.id = i.id_cliente
         join inscripcion_servicio ins on ins.id_inscripcion = i.id
         join servicio s on s.id = ins.id_exp_servicio
         join servicio_impuesto si on si.id_servicio = s.id
         join impuesto imp on imp.id = si.id_impuesto;

