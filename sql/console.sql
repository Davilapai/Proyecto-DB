-- 1 Experiencias disponibles por ciudad, estadio o partido

-- Por Ciudad
select c.nombre as Ciudad, count(e.id) as Cantidad
from experiencia e
         join partido p on p.id = e.id_partido
         join estadio es on es.id = p.id_estadio
         join ciudad c on c.id = es.id_ciudad
group by c.nombre;

-- Por Estadio
select es.nombre as Estadio, count(e.id) as Cantidad
from experiencia e
         join partido p on p.id = e.id_partido
         join estadio es on es.id = p.id_estadio
group by es.nombre;

-- Por Partido
select s.nombre || ' vs ' || s2.nombre as Partido,
       p.id                            as ID_partido,
       e.id                            as ID_experiencia,
       e.estado                        as Estado,
       e.cupos_disponibles             as Cupos_disponibles,
       e.cupos_totales                 as Cupos_totales,
       e.precio_base                   as Precio_base
from experiencia e
         join partido p on p.id = e.id_partido
         join seleccion s on s.id = p.id_seleccion_local
         join seleccion s2 on s2.id = p.id_seleccion_visitante;


-- 2 Clientes con mayor numero de inscripciones
select  c.id,
        c.nombre_completo   as Cliente,
        count(i.id)         as Total_Inscripciones

from cliente c
         join inscripcion i on i.id_cliente = c.id

group by c.id, c.nombre_completo
having count(i.id) = (
    select max(Total_Inscripciones)
    from (
             select count(*) as Total_Inscripciones
             from inscripcion
             group by id_cliente
         )
);

-- 3 Ingresos generados por cada guia (tarifa horaria * 4 horas por experiencia)
select g.id,
       g.nombre,
       SUM(
               CASE
                   WHEN g.nivel = 'BASICO' THEN 15
                   WHEN g.nivel = 'INTERMEDIO' THEN 30
                   WHEN g.nivel = 'EXPERTO' THEN 60
                   END
       ) * 4 AS Ingresos
from experiencia e
         join guia g on e.id_guia_principal = g.id
group by g.id, g.nombre;

-- 4 Experiencias mas demandadas (con menos cupos disponibles)
select *
from experiencia e
where e.cupos_disponibles = (select min(cupos_disponibles) from experiencia);

-- 5 Total de impuestos cobrados por pais sede
select pa.nombre as Pais_Sede,
       nvl(
               sum(
                       ins.cantidad * ins.costo_unitario * (imp.porcentaje / 100)
               ),
               0
       ) as Total_Impuestos
from pais pa
         left join ciudad ci on ci.id_pais = pa.id
         left join estadio es on es.id_ciudad = ci.id
         left join partido p on p.id_estadio = es.id
         left join experiencia e on e.id_partido = p.id
         left join inscripcion i on i.id_experiencia = e.id
         left join inscripcion_servicio ins on ins.id_inscripcion = i.id
         left join experiencia_servicio eserv on eserv.id = ins.id_exp_servicio
         left join servicio s on s.id = eserv.id_servicio
         left join servicio_impuesto si on si.id_servicio = s.id
         left join impuesto imp on imp.id = si.id_impuesto
group by pa.nombre
order by Total_Impuestos desc;

-- 6 Clientes con pagos pendientes
select c.nombre_completo,
       i.id as ID_Inscripcion,
       i.saldo_pendiente
from cliente c
         join inscripcion i on c.id = i.id_cliente
where i.saldo_pendiente > 0;

-- 7 Cupos disponibles por experiencia
select e.id as ID_Experiencia,
       s_local.nombre || ' vs ' || s_visita.nombre as Partido,
       e.cupos_totales,
       e.cupos_disponibles,
       (e.cupos_totales - e.cupos_disponibles) as Vendidos
from experiencia e
         join partido p on p.id = e.id_partido
         join seleccion s_local on s_local.id = p.id_seleccion_local
         join seleccion s_visita on s_visita.id = p.id_seleccion_visitante
order by e.id;
